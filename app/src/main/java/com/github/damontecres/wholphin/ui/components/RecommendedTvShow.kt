/**
 * The "recommended" tab of a TV show library
 */
@Composable
fun RecommendedTvShow(
    preferences: UserPreferences,
    parentId: UUID,
    onFocusPosition: (RowColumn) -> Unit,
    modifier: Modifier = Modifier,
    viewModel: RecommendedViewModel =
        hiltViewModel<RecommendedViewModel, RecommendedViewModel.Factory>(
            creationCallback = {
                it.create(
                    parentId = parentId,
                    suggestionsType = BaseItemKind.SERIES,
                    recommendedRows =
                        recommendedTvShowRows(
                            parentId,
                            preferences.appPreferences.homePagePreferences.enableRewatchingNextUp,
                        ),
                    viewOptions = HomeRowViewOptions(),
                    serviceTop10Type = BaseItemKind.SERIES,
                )
            },
        ),
) {
    RecommendedContent(
        preferences = preferences,
        viewModel = viewModel,
        onFocusPosition = onFocusPosition,
        modifier = modifier,
        headerModifier = HeaderUtils.recommendedModifier(),
        splitRecommendedTitles = true,
    )
}
